// Dumps dexlib2's opcode table as TSV, one row per opcode byte, for the
// cross-check in `readers/dex-reader/tests/dexlib2_opcodes.rs`.
//
// dexlib2 ships inside the baksmali fat jar. Regenerate the checked-in dump
// when the baksmali version changes:
//
//   java -cp <baksmali-fat.jar> readers/dex-reader/scripts/DumpDexlib2Opcodes.java \
//     > readers/dex-reader/tests/data/dexlib2-opcodes.tsv
//
// The jar path is the one the Nix `baksmali` wrapper runs (`cat $(which baksmali)`).
//
// Rows use the API 28 opcode table: dex 039, the first with const-method-handle
// and const-method-type. dexlib2 maps some unused bytes to odex-only opcodes
// (the -quick family, return-void-no-barrier). Those never appear in a .dex
// file, so the dump lists them as unused.

import com.android.tools.smali.dexlib2.Opcode;
import com.android.tools.smali.dexlib2.Opcodes;
import com.android.tools.smali.dexlib2.ReferenceType;

public class DumpDexlib2Opcodes {
    static final int API = 28;

    static String ref(int r) {
        switch (r) {
            case ReferenceType.STRING: return "string";
            case ReferenceType.TYPE: return "type";
            case ReferenceType.FIELD: return "field";
            case ReferenceType.METHOD: return "method";
            case ReferenceType.METHOD_PROTO: return "proto";
            case ReferenceType.CALL_SITE: return "call_site";
            case ReferenceType.METHOD_HANDLE: return "method_handle";
            // referenceType2 is -1, not NONE, for opcodes with one reference.
            case ReferenceType.NONE: case -1: return "none";
            default: throw new IllegalArgumentException("reference type " + r);
        }
    }

    static int bit(boolean b) {
        return b ? 1 : 0;
    }

    public static void main(String[] args) {
        Opcodes opcodes = Opcodes.forApi(API);
        System.out.println("# dexlib2 opcode table, Opcodes.forApi(" + API + "). Generated by"
                + " readers/dex-reader/scripts/DumpDexlib2Opcodes.java; do not edit.");
        System.out.println("# size is in 16-bit code units. Flags are 0/1.");
        System.out.println(String.join("\t", "value", "name", "format", "size", "ref", "ref2",
                "can_throw", "can_continue", "sets_result", "sets_register",
                "sets_wide_register"));
        for (int value = 0; value < 256; value++) {
            Opcode op = opcodes.getOpcodeByValue(value);
            if (op == null || op.odexOnly()) {
                System.out.println(String.format("0x%02x\tunused\t-\t-\t-\t-\t-\t-\t-\t-\t-", value));
                continue;
            }
            System.out.println(String.join("\t",
                    String.format("0x%02x", value),
                    op.name,
                    op.format.name().replaceFirst("^Format", ""),
                    Integer.toString(op.format.size / 2),
                    ref(op.referenceType),
                    ref(op.referenceType2),
                    Integer.toString(bit(op.canThrow())),
                    Integer.toString(bit(op.canContinue())),
                    Integer.toString(bit(op.setsResult())),
                    Integer.toString(bit(op.setsRegister())),
                    Integer.toString(bit(op.setsWideRegister()))));
        }
    }
}

"""Freeze a whole-app Android query model from the TaintBench models.

    python3 gen_android_model.py ../../taintbench/apps > android-privacy.json

Each TaintBench app's model names the methods that its ground-truth flows start and end at,
plus propagation through framework methods the flows cross. Most of those rules name framework
classes (TelephonyManager, SmsManager, HttpClient, Log, ...), and those carry over to any app.
This keeps the rules whose every `signature_match` names an Android, Java or Apache class, and
drops duplicates. The fdroid and apps suites have no ground truth; this gives their queries the
same notion of a leak TaintBench scores against.
"""

import json
import sys
from pathlib import Path

FRAMEWORK = ("Landroid/", "Ljava/", "Ljavax/", "Lorg/apache/", "Lorg/json/", "Ldalvik/")


def framework_only(gen: dict) -> bool:
    ws = gen.get("where", [])
    return bool(ws) and all(w.get("constraint") == "signature_match"
                            and str(w.get("parent", "")).startswith(FRAMEWORK) for w in ws)


def main() -> None:
    apps = Path(sys.argv[1])
    seen, gens, used = set(), [], []
    for model in sorted(apps.glob("*/model.json")):
        added = 0
        for g in json.loads(model.read_text()).get("model_generators", []):
            key = json.dumps(g, sort_keys=True)
            if framework_only(g) and key not in seen:
                seen.add(key)
                gens.append(g)
                added += 1
        if added:
            used.append(model.parent.name)
    out = {
        "description": [
            "Whole-app Android query model, generated by bench/suites/gen_android_model.py: the",
            "framework-class rules of the TaintBench app models, deduplicated.",
            f"From: {', '.join(used)}.",
        ],
        "model_generators": gens,
    }
    json.dump(out, sys.stdout, indent=2)
    print()
    kinds = {k: sum(1 for g in gens if k in g.get("model", {})) for k in ("sources", "sinks", "propagation")}
    print(f"{len(gens)} rules from {len(used)} apps: {kinds}", file=sys.stderr)


if __name__ == "__main__":
    main()

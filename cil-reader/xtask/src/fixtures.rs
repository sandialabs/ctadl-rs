//! `cargo xtask fixtures`: builds tests/fixtures from Cecil's .il/.cs test
//! sources (PLAN.md §5.2). We compile once and commit the binaries, never
//! modifying extern/cecil.
//!
//! - `.il` files are assembled with the standalone CoreCLR ilasm from the
//!   `runtime.<rid>.Microsoft.NETCore.ILAsm` NuGet package (a plain zip; no
//!   dotnet needed). Note the flag dialect: `-nologo -quiet -dll
//!   -output=<file>`, not the Mono-style `/dll /out:` Cecil's harness uses
//!   (CompilationService.cs:319-326).
//! - `.cs` files are compiled with a generated csproj per source (Release,
//!   `NET_CORE` define, library output named after the source — matching
//!   RoslynCompilationService). Requires `dotnet` on PATH (nix devshell).
//!
//! A manifest (tests/fixtures/manifest.toml) records source hashes so reruns
//! are idempotent and CI can check freshness.

use std::collections::hash_map::DefaultHasher;
use std::fmt::Write as _;
use std::hash::{Hash, Hasher};
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

const ILASM_VERSION: &str = "10.0.11";

pub fn run(root: &Path) -> ExitCode {
    let il_dir = root.join("extern/cecil/Test/Resources/il");
    let cs_dir = root.join("extern/cecil/Test/Resources/cs");
    let out_dir = root.join("tests/fixtures");
    std::fs::create_dir_all(&out_dir).unwrap();

    let mut manifest = String::from(
        "# Generated by `cargo xtask fixtures`. Maps fixture binaries to the\n\
         # hash of the Cecil source they were compiled from.\n",
    );
    let mut failed = false;

    // --- .il fixtures ---
    let ilasm = match ensure_ilasm(root) {
        Ok(path) => Some(path),
        Err(e) => {
            eprintln!("cannot set up ilasm: {e}");
            failed = true;
            None
        }
    };
    if let Some(ilasm) = &ilasm {
        let mut il_files: Vec<PathBuf> = std::fs::read_dir(&il_dir)
            .unwrap()
            .filter_map(|e| Some(e.ok()?.path()))
            .filter(|p| p.extension().is_some_and(|e| e == "il"))
            .collect();
        il_files.sort();
        for il in &il_files {
            let name = il.file_name().unwrap().to_str().unwrap();
            let out = out_dir.join(format!("{name}.dll"));
            let hash = file_hash(il);
            writeln!(manifest, "\"{name}.dll\" = \"{hash:016x}\"").unwrap();
            if out.exists() && manifest_entry_current(&out_dir, name, hash) {
                continue;
            }
            let status = Command::new(ilasm)
                .arg("-nologo")
                .arg("-quiet")
                .arg("-dll")
                .arg(format!("-output={}", out.display()))
                .arg(il)
                .output()
                .expect("run ilasm");
            if !status.status.success() {
                eprintln!(
                    "ilasm failed on {name}:\n{}{}",
                    String::from_utf8_lossy(&status.stdout),
                    String::from_utf8_lossy(&status.stderr)
                );
                failed = true;
            } else {
                println!("assembled {name}.dll");
            }
        }
    }

    // --- .cs fixtures ---
    if which("dotnet") {
        let mut cs_files: Vec<PathBuf> = std::fs::read_dir(&cs_dir)
            .unwrap()
            .filter_map(|e| Some(e.ok()?.path()))
            .filter(|p| p.extension().is_some_and(|e| e == "cs"))
            .collect();
        cs_files.sort();
        for cs in &cs_files {
            let name = cs.file_name().unwrap().to_str().unwrap();
            let out = out_dir.join(format!("{name}.dll"));
            let hash = file_hash(cs);
            writeln!(manifest, "\"{name}.dll\" = \"{hash:016x}\"").unwrap();
            if out.exists() && manifest_entry_current(&out_dir, name, hash) {
                continue;
            }
            match compile_cs(root, cs, &out) {
                Ok(()) => println!("compiled {name}.dll"),
                Err(e) => {
                    eprintln!("csc failed on {name}: {e}");
                    failed = true;
                }
            }
        }
    } else {
        eprintln!("warning: dotnet not on PATH; skipping .cs fixtures");
    }

    std::fs::write(out_dir.join("manifest.toml"), manifest).unwrap();
    if failed {
        ExitCode::FAILURE
    } else {
        ExitCode::SUCCESS
    }
}

fn manifest_entry_current(out_dir: &Path, name: &str, hash: u64) -> bool {
    let Ok(manifest) = std::fs::read_to_string(out_dir.join("manifest.toml")) else {
        return false;
    };
    manifest
        .lines()
        .any(|l| l.starts_with(&format!("\"{name}.dll\"")) && l.contains(&format!("{hash:016x}")))
}

fn file_hash(path: &Path) -> u64 {
    let data = std::fs::read(path).unwrap();
    let mut h = DefaultHasher::new();
    data.hash(&mut h);
    h.finish()
}

fn which(bin: &str) -> bool {
    std::env::var_os("PATH").is_some_and(|paths| {
        std::env::split_paths(&paths).any(|p| p.join(bin).is_file())
    })
}

/// Downloads and extracts the standalone ilasm if not already cached under
/// target/ilasm.
fn ensure_ilasm(root: &Path) -> Result<PathBuf, String> {
    let rid = match (std::env::consts::OS, std::env::consts::ARCH) {
        ("macos", "aarch64") => "osx-arm64",
        ("macos", "x86_64") => "osx-x64",
        ("linux", "aarch64") => "linux-arm64",
        ("linux", "x86_64") => "linux-x64",
        other => return Err(format!("unsupported platform {other:?}")),
    };
    let cache = root.join("target/ilasm").join(ILASM_VERSION).join(rid);
    let bin = cache.join(format!("runtimes/{rid}/native/ilasm"));
    if bin.is_file() {
        return Ok(bin);
    }
    std::fs::create_dir_all(&cache).map_err(|e| e.to_string())?;
    let url = format!(
        "https://www.nuget.org/api/v2/package/runtime.{rid}.Microsoft.NETCore.ILAsm/{ILASM_VERSION}"
    );
    let nupkg = cache.join("ilasm.nupkg");
    println!("downloading {url}");
    let status = Command::new("curl")
        .args(["-sSL", "--max-time", "300", "-o"])
        .arg(&nupkg)
        .arg(&url)
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err("curl failed".into());
    }
    let status = Command::new("unzip")
        .arg("-o")
        .arg("-q")
        .arg(&nupkg)
        .current_dir(&cache)
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err("unzip failed".into());
    }
    let status = Command::new("chmod")
        .arg("+x")
        .arg(&bin)
        .status()
        .map_err(|e| e.to_string())?;
    if !status.success() {
        return Err("chmod failed".into());
    }
    Ok(bin)
}

/// Mirrors RoslynCompilationService: library, Release, NET_CORE define,
/// assembly name = source name without extension.
fn compile_cs(root: &Path, source: &Path, out: &Path) -> Result<(), String> {
    let stem = source.file_stem().unwrap().to_str().unwrap();
    let build_dir = root.join("target/cs-fixtures").join(stem);
    let _ = std::fs::remove_dir_all(&build_dir);
    std::fs::create_dir_all(&build_dir).map_err(|e| e.to_string())?;

    let csproj = format!(
        r#"<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <AssemblyName>{stem}</AssemblyName>
    <Configuration>Release</Configuration>
    <DefineConstants>NET_CORE</DefineConstants>
    <Optimize>true</Optimize>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
    <Nullable>disable</Nullable>
    <LangVersion>latest</LangVersion>
    <NoWarn>CS0169;CS0649;CS0067;CS0414;CS0659;CS0661</NoWarn>
    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="{src}" />
    <PackageReference Include="System.Security.AccessControl" Version="6.0.1" />
  </ItemGroup>
</Project>
"#,
        src = source.display(),
    );
    std::fs::write(build_dir.join(format!("{stem}.csproj")), csproj).map_err(|e| e.to_string())?;

    let output = Command::new("dotnet")
        .args(["build", "-c", "Release", "--nologo", "-v", "q"])
        .current_dir(&build_dir)
        .output()
        .map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(format!(
            "{}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let built = build_dir.join("bin/Release").join(format!("{stem}.dll"));
    std::fs::copy(&built, out).map_err(|e| format!("copy {}: {e}", built.display()))?;
    Ok(())
}

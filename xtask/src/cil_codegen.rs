//! `cargo xtask cil codegen`: generates
//! readers/cil-reader/crates/cil-reader/src/cil/opcodes.rs from the pinned
//! Cecil sources, so our opcode table provably matches Cecil's:
//!
//! - `Mono.Cecil.Cil/Code.cs` — the `Code` enum order (names index into it)
//! - `Mono.Cecil.Cil/OpCodes.cs` — the ~219 opcode definitions
//! - `Mono.Cecil.Cil/OpCode.cs` — the packed `OpCodeNames` byte table

use std::fmt::Write as _;
use std::path::Path;

struct OpDef {
    field: String,
    op1: u8,
    op2: u8,
    code: String,
    flow_control: String,
    opcode_type: String,
    operand_type: String,
    stack_pop: String,
    stack_push: String,
}

/// `cecil` is the Cecil checkout; `cil_root` the cil-reader directory.
pub fn run(cecil: &Path, cil_root: &Path) -> bool {
    let cil_dir = cecil.join("Mono.Cecil.Cil");
    let code_cs = std::fs::read_to_string(cil_dir.join("Code.cs")).expect("read Code.cs");
    let opcodes_cs = std::fs::read_to_string(cil_dir.join("OpCodes.cs")).expect("read OpCodes.cs");
    let opcode_cs = std::fs::read_to_string(cil_dir.join("OpCode.cs")).expect("read OpCode.cs");

    let codes = parse_code_enum(&code_cs);
    let names = parse_names(&opcode_cs);
    let defs = parse_opcodes(&opcodes_cs);
    assert_eq!(codes.len(), names.len(), "Code enum vs names table length");
    assert_eq!(codes.len(), defs.len(), "Code enum vs OpCodes definitions");

    let out = emit(&codes, &names, &defs);
    let out_path = cil_root.join("crates/cil-reader/src/cil/opcodes.rs");
    std::fs::create_dir_all(out_path.parent().unwrap()).unwrap();
    std::fs::write(&out_path, out).expect("write opcodes.rs");
    println!("generated {} ({} opcodes)", out_path.display(), defs.len());
    true
}

fn parse_code_enum(src: &str) -> Vec<String> {
    let body = src
        .split("public enum Code {")
        .nth(1)
        .expect("Code enum")
        .split('}')
        .next()
        .unwrap();
    body.split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(str::to_string)
        .collect()
}

fn parse_names(src: &str) -> Vec<String> {
    let body = src
        .split("var table = new byte [] {")
        .nth(1)
        .expect("names table")
        .split("};")
        .next()
        .unwrap();
    let bytes: Vec<u8> = body
        .split(',')
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .map(|s| s.parse::<u8>().expect("byte"))
        .collect();
    let mut names = Vec::new();
    let mut p = 0;
    while p < bytes.len() {
        let len = bytes[p] as usize;
        p += 1;
        names.push(String::from_utf8(bytes[p..p + len].to_vec()).unwrap());
        p += len;
    }
    names
}

fn parse_opcodes(src: &str) -> Vec<OpDef> {
    let mut defs = Vec::new();
    for chunk in src.split("public static readonly OpCode ").skip(1) {
        let field = chunk.split('=').next().unwrap().trim().to_string();
        let args = chunk
            .split("new OpCode (")
            .nth(1)
            .expect("OpCode ctor")
            .split(");")
            .next()
            .unwrap();
        // First ctor arg: 0xXX << 0 | 0xYY << 8 | (byte) Code.C << 16 | (byte) FlowControl.F << 24
        // Second:         (byte) OpCodeType.T << 0 | (byte) OperandType.O << 8
        //                 | (byte) StackBehaviour.Pop << 16 | (byte) StackBehaviour.Push << 24
        let halves: Vec<&str> = args.splitn(2, ',').collect();
        assert_eq!(halves.len(), 2, "opcode {field}: {args}");
        let parts: Vec<&str> = halves
            .iter()
            .flat_map(|h| h.split('|'))
            .map(str::trim)
            .collect();
        assert_eq!(parts.len(), 8, "opcode {field}: {args}");
        let hex = |s: &str| {
            let h = s.split("<<").next().unwrap().trim();
            u8::from_str_radix(h.trim_start_matches("0x"), 16).expect("hex byte")
        };
        let member = |s: &str, prefix: &str| {
            s.split(prefix)
                .nth(1)
                .unwrap_or_else(|| panic!("opcode {field}: expected {prefix} in {s}"))
                .split("<<")
                .next()
                .unwrap()
                .trim()
                .to_string()
        };
        defs.push(OpDef {
            op1: hex(parts[0]),
            op2: hex(parts[1]),
            code: member(parts[2], "Code."),
            flow_control: member(parts[3], "FlowControl."),
            opcode_type: member(parts[4], "OpCodeType."),
            operand_type: member(parts[5], "OperandType."),
            stack_pop: member(parts[6], "StackBehaviour."),
            stack_push: member(parts[7], "StackBehaviour."),
            field,
        });
    }
    defs
}

fn emit(codes: &[String], names: &[String], defs: &[OpDef]) -> String {
    let mut s = String::new();
    s.push_str(
        "//! CIL opcode table. GENERATED by `cargo xtask cil codegen` from the pinned\n\
         //! Cecil sources (`Mono.Cecil.Cil/{Code,OpCode,OpCodes}.cs`) — do not edit.\n\
         //!\n\
         //! Unlike Cecil, whose `OpCode` constructor self-registers into static\n\
         //! arrays (`OpCode.cs:159-162`), this is a plain const table.\n\n\
         #![allow(non_camel_case_types)]\n\n",
    );

    // Code enum
    s.push_str("/// `Mono.Cecil.Cil.Code`: one variant per opcode, in Cecil order.\n");
    s.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n#[repr(u16)]\npub enum Code {\n",
    );
    for c in codes {
        writeln!(s, "    {c},").unwrap();
    }
    s.push_str("}\n\n");

    for (rust, cecil, variants) in [
        (
            "FlowControl",
            "Mono.Cecil.Cil.FlowControl",
            vec![
                "Branch",
                "Break",
                "Call",
                "Cond_Branch",
                "Meta",
                "Next",
                "Phi",
                "Return",
                "Throw",
            ],
        ),
        (
            "OpCodeType",
            "Mono.Cecil.Cil.OpCodeType",
            vec![
                "Annotation",
                "Macro",
                "Nternal",
                "Objmodel",
                "Prefix",
                "Primitive",
            ],
        ),
        (
            "OperandType",
            "Mono.Cecil.Cil.OperandType",
            vec![
                "InlineBrTarget",
                "InlineField",
                "InlineI",
                "InlineI8",
                "InlineMethod",
                "InlineNone",
                "InlinePhi",
                "InlineR",
                "InlineSig",
                "InlineString",
                "InlineSwitch",
                "InlineTok",
                "InlineType",
                "InlineVar",
                "InlineArg",
                "ShortInlineBrTarget",
                "ShortInlineI",
                "ShortInlineR",
                "ShortInlineVar",
                "ShortInlineArg",
            ],
        ),
        (
            "StackBehaviour",
            "Mono.Cecil.Cil.StackBehaviour",
            vec![
                "Pop0",
                "Pop1",
                "Pop1_pop1",
                "Popi",
                "Popi_pop1",
                "Popi_popi",
                "Popi_popi8",
                "Popi_popi_popi",
                "Popi_popr4",
                "Popi_popr8",
                "Popref",
                "Popref_pop1",
                "Popref_popi",
                "Popref_popi_popi",
                "Popref_popi_popi8",
                "Popref_popi_popr4",
                "Popref_popi_popr8",
                "Popref_popi_popref",
                "PopAll",
                "Push0",
                "Push1",
                "Push1_push1",
                "Pushi",
                "Pushi8",
                "Pushr4",
                "Pushr8",
                "Pushref",
                "Varpop",
                "Varpush",
            ],
        ),
    ] {
        writeln!(s, "/// `{cecil}`.").unwrap();
        writeln!(
            s,
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n#[repr(u8)]\npub enum {rust} {{"
        )
        .unwrap();
        for v in variants {
            writeln!(s, "    {v},").unwrap();
        }
        s.push_str("}\n\n");
    }

    // OpCode struct
    s.push_str(
        "/// One CIL opcode. `op1 == 0xff` marks a one-byte opcode whose encoding is\n\
         /// `op2`; otherwise the encoding is the two bytes `op1 op2` (op1 is 0xfe).\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct OpCode {\n\
         \x20   pub code: Code,\n\
         \x20   pub op1: u8,\n\
         \x20   pub op2: u8,\n\
         \x20   pub flow_control: FlowControl,\n\
         \x20   pub opcode_type: OpCodeType,\n\
         \x20   pub operand_type: OperandType,\n\
         \x20   pub stack_pop: StackBehaviour,\n\
         \x20   pub stack_push: StackBehaviour,\n\
         }\n\n\
         impl OpCode {\n\
         \x20   pub fn name(self) -> &'static str {\n\
         \x20       NAMES[self.code as usize]\n\
         \x20   }\n\n\
         \x20   /// Encoded size in bytes (1 or 2).\n\
         \x20   pub fn size(self) -> u32 {\n\
         \x20       if self.op1 == 0xff { 1 } else { 2 }\n\
         \x20   }\n\n\
         \x20   /// The opcode value as in ECMA-335 (e.g. 0xfe01 for ceq).\n\
         \x20   pub fn value(self) -> u16 {\n\
         \x20       if self.op1 == 0xff { self.op2 as u16 } else { ((self.op1 as u16) << 8) | self.op2 as u16 }\n\
         \x20   }\n\
         }\n\n\
         impl std::fmt::Display for OpCode {\n\
         \x20   fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {\n\
         \x20       f.write_str(self.name())\n\
         \x20   }\n\
         }\n\n",
    );

    // Names, from Cecil's packed table (indexed by Code).
    s.push_str("/// Opcode names, indexed by `Code` (Cecil `OpCodeNames.names`).\n");
    writeln!(s, "pub static NAMES: [&str; {}] = [", names.len()).unwrap();
    for n in names {
        writeln!(s, "    \"{n}\",").unwrap();
    }
    s.push_str("];\n\n");

    // Opcode consts, e.g. pub const NOP: OpCode = ...
    for d in defs {
        let konst = const_name(&d.field);
        writeln!(
            s,
            "pub const {konst}: OpCode = OpCode {{ code: Code::{code}, op1: 0x{op1:02x}, op2: 0x{op2:02x}, flow_control: FlowControl::{fc}, opcode_type: OpCodeType::{ot}, operand_type: OperandType::{opt}, stack_pop: StackBehaviour::{pop}, stack_push: StackBehaviour::{push} }};",
            code = d.code,
            op1 = d.op1,
            op2 = d.op2,
            fc = d.flow_control,
            ot = d.opcode_type,
            opt = d.operand_type,
            pop = d.stack_pop,
            push = d.stack_push,
        )
        .unwrap();
    }
    s.push('\n');

    // Decode tables.
    let mut one_byte: Vec<Option<&OpDef>> = vec![None; 0xe0 + 1];
    let mut two_byte: Vec<Option<&OpDef>> = vec![None; 0x1e + 1];
    for d in defs {
        if d.op1 == 0xff {
            one_byte[d.op2 as usize] = Some(d);
        } else {
            assert_eq!(d.op1, 0xfe, "two-byte prefix");
            two_byte[d.op2 as usize] = Some(d);
        }
    }
    let emit_table = |s: &mut String, name: &str, table: &[Option<&OpDef>]| {
        writeln!(
            s,
            "pub static {name}: [Option<OpCode>; {}] = [",
            table.len()
        )
        .unwrap();
        for entry in table {
            match entry {
                Some(d) => writeln!(s, "    Some({}),", const_name(&d.field)).unwrap(),
                None => s.push_str("    None,\n"),
            }
        }
        s.push_str("];\n\n");
    };
    s.push_str("/// One-byte opcodes indexed by their encoding (Cecil `OneByteOpCode`).\n");
    emit_table(&mut s, "ONE_BYTE", &one_byte);
    s.push_str("/// Two-byte (0xfe-prefixed) opcodes indexed by their second byte\n/// (Cecil `TwoBytesOpCode`).\n");
    emit_table(&mut s, "TWO_BYTE", &two_byte);

    s
}

/// `Ldarg_0` → `LDARG_0`, `Nop` → `NOP`.
fn const_name(field: &str) -> String {
    field.to_uppercase()
}
